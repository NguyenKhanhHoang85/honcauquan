export const GENERATE_SEPTEMBER_DAILY_DATA = (): DailyReportItem[] => {
  const days: DailyReportItem[] = [];
  const baseRevenues = [
    7200000, 8400000, 7900000, 8900000, 11500000, 15200000, 16800000, // Week 1 (T2-CN)
    7800000, 8100000, 8600000, 9200000, 12800000, 17100000, 18500000, // Week 2
    8300000, 8700000, 9100000, 9800000, 13400000, 17900000, 19200000, // Week 3
    9400000, 10200000, // Today 22/09 and upcoming
  ];

  for (let i = 1; i <= 22; i++) {
    const rev = baseRevenues[i - 1] || 8500000;
    const orders = Math.floor(rev / 380000);
    const guests = Math.floor(orders * 2.8);
    const dayStr = i < 10 ? `0${i}` : `${i}`;
    days.push({
      date: `2026-09-${dayStr}`,
      dayLabel: `${dayStr}/09`,
      revenue: rev,
      orderCount: orders,
      guestCount: guests,
      vietQrRevenue: Math.round(rev * 0.48),
      momoRevenue: Math.round(rev * 0.22),
      vnpayRevenue: Math.round(rev * 0.15),
      cashRevenue: Math.round(rev * 0.15),
      seafoodRevenue: Math.round(rev * 0.62),
      coffeeDrinkRevenue: Math.round(rev * 0.25),
      foodRevenue: Math.round(rev * 0.13),
    });
  }
  return days;
};

